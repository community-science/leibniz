"""Canonical benchmark evaluation result bundles."""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass

from leibniz.architectures import ArchitectureManifest
from leibniz.benchmarks import BenchmarkManifest
from leibniz.content import ContentDigest
from leibniz.documents import ContentEncodingError, load_object_document
from leibniz.identifiers import ProtocolIdentifier
from leibniz.measurements import MeasurementDataset
from leibniz.model_inspection import ModelInspectionRecord
from leibniz.model_manifests import ModelArtifactManifest
from leibniz.records import FieldSpec, RecordExtractor, RecordSpec
from leibniz.views import MeasurementScoreView

__all__ = [
    "BenchmarkEvaluationBundle",
    "BenchmarkEvaluationBundleDocument",
    "BenchmarkEvaluationBundleValidationError",
]

_evaluation_bundle_record = RecordSpec(
    fields={
        "format": FieldSpec(kind="literal", literal="leibniz.benchmark-evaluation"),
        "format_version": FieldSpec(kind="integer"),
        "id": FieldSpec(kind="identifier"),
        "run_slug": FieldSpec(kind="string"),
        "benchmark_manifest": FieldSpec(kind="record"),
        "architecture_manifest": FieldSpec(kind="record"),
        "model_manifest": FieldSpec(kind="record"),
        "model_checkpoint": FieldSpec(kind="record"),
        "model_inspection": FieldSpec(kind="record"),
        "measurement_dataset": FieldSpec(kind="record"),
        "measurement_score_view": FieldSpec(kind="record"),
        "sampled_competence": FieldSpec(kind="record"),
        "evaluation_protocol": FieldSpec(kind="record"),
        "evaluation_seed": FieldSpec(kind="integer"),
        "evaluation_curriculum": FieldSpec(kind="record"),
        "throughput": FieldSpec(kind="record"),
    }
)


class BenchmarkEvaluationBundleValidationError(ValueError):
    """Raised when an accepted benchmark evaluation bundle is invalid."""


_record = RecordExtractor(BenchmarkEvaluationBundleValidationError)


@dataclass(frozen=True, slots=True)
class BenchmarkEvaluationBundle:
    """Accepted benchmark result evidence generated by the evaluator."""

    id: ProtocolIdentifier
    run_slug: str
    benchmark_manifest: BenchmarkManifest
    architecture_manifest: ArchitectureManifest
    model_manifest: ModelArtifactManifest
    model_checkpoint: Mapping[str, object]
    model_inspection: ModelInspectionRecord
    measurement_dataset: MeasurementDataset
    measurement_score_view: MeasurementScoreView
    sampled_competence: Mapping[str, object]
    evaluation_protocol: Mapping[str, object]
    evaluation_seed: int
    evaluation_curriculum: Mapping[str, object]
    throughput: Mapping[str, object]

    def __post_init__(self) -> None:
        try:
            self.id.require_unreleased()
        except ValueError as error:
            raise BenchmarkEvaluationBundleValidationError(str(error)) from error
        if not str(self.id.name).startswith("benchmark-evaluations."):
            raise BenchmarkEvaluationBundleValidationError(
                "id must be a valid benchmark evaluation id"
            )
        if not self.run_slug:
            raise BenchmarkEvaluationBundleValidationError("run_slug must be nonempty")
        if type(self.evaluation_seed) is not int or self.evaluation_seed < 0:
            raise BenchmarkEvaluationBundleValidationError(
                "evaluation_seed must be a nonnegative integer"
            )
        self.validate_sources()

    @classmethod
    def from_record(cls, record: Mapping[str, object]) -> BenchmarkEvaluationBundle:
        try:
            validated = _evaluation_bundle_record.validate(record)
            benchmark_manifest = BenchmarkManifest.from_record(
                _record.mapping(validated["benchmark_manifest"], "benchmark_manifest")
            )
            architecture_manifest = ArchitectureManifest.from_record(
                _record.mapping(validated["architecture_manifest"], "architecture_manifest")
            )
            model_manifest = ModelArtifactManifest.from_record(
                _record.mapping(validated["model_manifest"], "model_manifest"),
                architecture_manifest=architecture_manifest,
            )
            model_inspection = ModelInspectionRecord.from_record(
                _record.mapping(validated["model_inspection"], "model_inspection")
            )
            measurement_dataset = MeasurementDataset.from_record(
                _record.mapping(validated["measurement_dataset"], "measurement_dataset")
            )
            measurement_score_view = MeasurementScoreView.from_record(
                _record.mapping(validated["measurement_score_view"], "measurement_score_view"),
                dataset=measurement_dataset,
            )
        except ValueError as error:
            raise BenchmarkEvaluationBundleValidationError(str(error)) from error
        return cls(
            id=_record.identifier(validated["id"], "id"),
            run_slug=_record.non_empty_string(validated["run_slug"], "run_slug"),
            benchmark_manifest=benchmark_manifest,
            architecture_manifest=architecture_manifest,
            model_manifest=model_manifest,
            model_checkpoint=_record.mapping(validated["model_checkpoint"], "model_checkpoint"),
            model_inspection=model_inspection,
            measurement_dataset=measurement_dataset,
            measurement_score_view=measurement_score_view,
            sampled_competence=_record.mapping(
                validated["sampled_competence"],
                "sampled_competence",
            ),
            evaluation_protocol=_record.mapping(
                validated["evaluation_protocol"],
                "evaluation_protocol",
            ),
            evaluation_seed=_record.integer(validated["evaluation_seed"], "evaluation_seed"),
            evaluation_curriculum=_record.mapping(
                validated["evaluation_curriculum"],
                "evaluation_curriculum",
            ),
            throughput=_record.mapping(validated["throughput"], "throughput"),
        )

    @property
    def digest(self) -> ContentDigest:
        return ContentDigest.from_value(self.to_record())

    def validate_sources(self) -> None:
        if self.benchmark_manifest.id != _bundle_benchmark_id(
            self.measurement_dataset,
            sampled_competence=self.sampled_competence,
        ):
            raise BenchmarkEvaluationBundleValidationError(
                "measurement_dataset benchmark_id does not match benchmark manifest"
            )
        try:
            self.measurement_dataset.validate_manifest(self.benchmark_manifest)
            self.model_manifest.validate_architecture(self.architecture_manifest)
        except ValueError as error:
            raise BenchmarkEvaluationBundleValidationError(str(error)) from error
        self._validate_model_checkpoint()
        if not self.model_inspection.architecture.matches_record(
            self.architecture_manifest.to_record()
        ):
            raise BenchmarkEvaluationBundleValidationError(
                "model_inspection architecture does not match architecture manifest"
            )
        if (
            self.model_inspection.model_manifest is not None
            and not self.model_inspection.model_manifest.matches_record(
                self.model_manifest.to_record()
            )
        ):
            raise BenchmarkEvaluationBundleValidationError(
                "model_inspection model_manifest does not match model manifest"
            )
        if (
            self.measurement_score_view.source_dataset_digest
            != self.measurement_dataset.digest
        ):
            raise BenchmarkEvaluationBundleValidationError(
                "measurement_score_view source_dataset_digest does not match dataset"
            )
        expected_score_view = MeasurementScoreView.from_dataset(
            id=self.measurement_score_view.id,
            dataset=self.measurement_dataset,
        )
        if self.measurement_score_view != expected_score_view:
            raise BenchmarkEvaluationBundleValidationError(
                "measurement_score_view is not derived from measurement_dataset"
            )
        _validate_inference_cost_measurement(
            self.throughput,
            phase="checkpoint_evaluation",
        )

    def _validate_model_checkpoint(self) -> None:
        if self.model_checkpoint.get("kind") != "model-checkpoint":
            raise BenchmarkEvaluationBundleValidationError(
                "model_checkpoint kind must be model-checkpoint"
            )
        _record.non_empty_string(self.model_checkpoint.get("path"), "model_checkpoint.path")
        _record.non_empty_string(
            self.model_checkpoint.get("manifest_path"),
            "model_checkpoint.manifest_path",
        )
        checkpoint_digest = ContentDigest.from_string(
            self.model_checkpoint.get("digest"),
            field="model_checkpoint.digest",
            error_type=BenchmarkEvaluationBundleValidationError,
        )
        if str(checkpoint_digest) == str(self.model_manifest.digest):
            raise BenchmarkEvaluationBundleValidationError(
                "model_checkpoint digest must identify weights, not the model manifest"
            )
        manifest_digest = ContentDigest.from_string(
            self.model_checkpoint.get("manifest_digest"),
            field="model_checkpoint.manifest_digest",
            error_type=BenchmarkEvaluationBundleValidationError,
        )
        if manifest_digest != self.model_manifest.digest:
            raise BenchmarkEvaluationBundleValidationError(
                "model_checkpoint manifest_digest does not match model_manifest"
            )
        step = _record.integer(self.model_checkpoint.get("step"), "model_checkpoint.step")
        validation_check = _record.integer(
            self.model_checkpoint.get("validation_check"),
            "model_checkpoint.validation_check",
        )
        validation_loss = self.model_checkpoint.get("validation_loss")
        if step < 0:
            raise BenchmarkEvaluationBundleValidationError(
                "model_checkpoint.step must be nonnegative"
            )
        if validation_check < 0:
            raise BenchmarkEvaluationBundleValidationError(
                "model_checkpoint.validation_check must be nonnegative"
            )
        if (
            not isinstance(validation_loss, int | float)
            or isinstance(validation_loss, bool)
            or not math.isfinite(validation_loss)
        ):
            raise BenchmarkEvaluationBundleValidationError(
                "model_checkpoint.validation_loss must be a finite number"
            )

    def to_record(self) -> dict[str, object]:
        record: dict[str, object] = {
            "format": "leibniz.benchmark-evaluation",
            "format_version": 1,
            "id": str(self.id),
            "run_slug": self.run_slug,
            "benchmark_manifest": self.benchmark_manifest.to_record(),
            "architecture_manifest": self.architecture_manifest.to_record(),
            "model_manifest": self.model_manifest.to_record(),
            "model_checkpoint": dict(self.model_checkpoint),
            "model_inspection": self.model_inspection.to_record(),
            "measurement_dataset": self.measurement_dataset.to_record(),
            "measurement_score_view": self.measurement_score_view.to_record(),
            "sampled_competence": dict(self.sampled_competence),
            "evaluation_protocol": dict(self.evaluation_protocol),
            "evaluation_seed": self.evaluation_seed,
            "evaluation_curriculum": dict(self.evaluation_curriculum),
            "throughput": dict(self.throughput),
        }
        return record


@dataclass(frozen=True, slots=True)
class BenchmarkEvaluationBundleDocument:
    """A loaded accepted benchmark evaluation bundle and its digest."""

    bundle: BenchmarkEvaluationBundle
    digest: ContentDigest

    @classmethod
    def from_bytes(cls, data: bytes) -> BenchmarkEvaluationBundleDocument:
        try:
            record = load_object_document(data, description="benchmark evaluation bundle")
        except ContentEncodingError as error:
            raise BenchmarkEvaluationBundleValidationError(str(error)) from error
        bundle = BenchmarkEvaluationBundle.from_record(record)
        return cls(bundle=bundle, digest=bundle.digest)


def _single_benchmark_id(dataset: MeasurementDataset) -> ProtocolIdentifier:
    benchmark_ids = frozenset(
        measurement.benchmark_id for measurement in dataset.measurements
    )
    if len(benchmark_ids) != 1:
        raise BenchmarkEvaluationBundleValidationError(
            "measurement_dataset must contain one benchmark id"
        )
    return next(iter(benchmark_ids))


def _bundle_benchmark_id(
    dataset: MeasurementDataset,
    *,
    sampled_competence: Mapping[str, object],
) -> ProtocolIdentifier:
    if dataset.measurements:
        return _single_benchmark_id(dataset)
    if sampled_competence.get("competence_value_kind") != "validated-bits":
        raise BenchmarkEvaluationBundleValidationError(
            "measurement_dataset must contain one benchmark id"
        )
    try:
        return ProtocolIdentifier.parse(
            _record.non_empty_string(
                sampled_competence.get("benchmark_id"),
                "sampled_competence.benchmark_id",
            )
        )
    except ValueError as error:
        raise BenchmarkEvaluationBundleValidationError(str(error)) from error


def _validate_inference_cost_measurement(
    throughput: Mapping[str, object],
    *,
    phase: str,
) -> None:
    phase_record = _record.mapping(throughput.get(phase), f"throughput.{phase}")
    measurement = _record.mapping(
        phase_record.get("inference_cost_measurement"),
        f"throughput.{phase}.inference_cost_measurement",
    )
    abstract_flops = _record.integer(
        measurement.get("abstract_flops"),
        f"throughput.{phase}.inference_cost_measurement.abstract_flops",
    )
    if abstract_flops < 0:
        raise BenchmarkEvaluationBundleValidationError(
            f"throughput.{phase}.inference_cost_measurement.abstract_flops must be nonnegative"
        )
    sample_count = _record.integer(
        phase_record.get("inference_cost_sample_count"),
        f"throughput.{phase}.inference_cost_sample_count",
    )
    if sample_count < 1:
        raise BenchmarkEvaluationBundleValidationError(
            f"throughput.{phase}.inference_cost_sample_count must be positive"
        )
